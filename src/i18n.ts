export type I18nKey = Key
const tables: Record<Lang, Record<Key, string>> = { fr, en }

let current: Lang = 'fr'
export const setLang = (l: Lang) => {
  current = l
  document.documentElement.lang = l
}

export function t(key: Key, params?: Record<string, string | number>, lang: Lang = current) {
  let s = tables[lang][key] ?? key
  if (params) for (const k in params) s = s.replaceAll(`{${k}}`, String(params[k]))
  return s
}
